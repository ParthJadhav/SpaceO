#!/usr/bin/env node
// Generate Sources/SpaceOMCP/Playbook.swift from docs/playbook/*.md.
//
// Regenerate after editing any playbook Markdown, then commit both the sources and the output:
//
//     node scripts/generate-playbook.mjs
//
// No dependencies. The output is committed so the Swift build never needs Node;
// Tests/SpaceOKitTests/PlaybookTests.swift fails when the two drift.

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourceDir = join(repoRoot, "docs", "playbook");
const outputPath = join(repoRoot, "Sources", "SpaceOMCP", "Playbook.swift");

// README.md documents this generator for maintainers; it is not part of the agent playbook.
const excluded = new Set(["README.md"]);

// Prompts advertised by the server, each backed by one document. Kept here, next to the
// documents they reference, so a renamed file fails generation instead of shipping a dangling
// prompt.
const prompts = [
  {
    name: "drive-app",
    description: "Drive a native macOS app on a SpaceO virtual display: create, open, read, act, verify, destroy, with the error-recovery loop.",
    documentName: "drive-app",
    arguments: [{ name: "app", description: "App name, bundle id, or .app path to open.", required: true }],
  },
  {
    name: "drive-web",
    description: "Drive a web page in SpaceO's managed Chromium: open_url, targets, web indices, and what synthetic input cannot do.",
    documentName: "drive-web",
    arguments: [{ name: "url", description: "The URL to open.", required: true }],
  },
  {
    name: "hand-off-to-human",
    description: "Pause for a human (2FA, ambiguous destructive step), wait safely, and resume from the handoff note.",
    documentName: "hand-off-to-human",
    arguments: [{ name: "reason", description: "One line the human sees on the session tile explaining why the agent paused.", required: true }],
  },
];

/** Title: the first `# ` heading, skipping YAML frontmatter. Falls back to the name. */
function titleOf(markdown, name) {
  let lines = markdown.split("\n");
  if (lines[0] === "---") {
    const end = lines.indexOf("---", 1);
    if (end > 0) lines = lines.slice(end + 1);
  }
  const heading = lines.find((line) => line.startsWith("# "));
  return heading ? heading.slice(2).trim() : name;
}

/**
 * A raw multi-line literal whose delimiter cannot occur in the content. Swift ends a raw string
 * at `"""` followed by exactly N `#`, and treats `\` followed by N `#` as an escape, so N is one
 * more than the longest run of `#` after either sequence in the content.
 */
function rawLiteral(text) {
  let longest = 0;
  for (const match of text.matchAll(/(?:"""|\\)(#*)/g)) {
    longest = Math.max(longest, match[1].length);
  }
  const hashes = "#".repeat(longest + 1);
  // The closing delimiter's own line is not part of the value, so a trailing newline in the
  // file needs one extra empty line to survive.
  return `${hashes}"""\n${text}\n"""${hashes}`;
}

function swiftString(text) {
  return JSON.stringify(text);
}

const files = readdirSync(sourceDir)
  .filter((file) => file.endsWith(".md") && !excluded.has(file))
  .sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));

const documents = files.map((file) => {
  const name = file.slice(0, -".md".length);
  const markdown = readFileSync(join(sourceDir, file), "utf8");
  if (markdown.trim().length === 0) throw new Error(`${file} is empty`);
  return { name, uri: `spaceo://docs/${name}`, title: titleOf(markdown, name), markdown };
});

const names = new Set(documents.map((document) => document.name));
for (const prompt of prompts) {
  if (!names.has(prompt.documentName)) {
    throw new Error(`prompt ${prompt.name} references missing document ${prompt.documentName}`);
  }
}

const out = [];
out.push("// Generated by scripts/generate-playbook.mjs — do not edit.");
out.push("// Source: docs/playbook/*.md. Regenerate with `node scripts/generate-playbook.mjs`.");
out.push("");
out.push("/// One agent-facing playbook document, served as the MCP resource at `uri`.");
out.push("public struct PlaybookDocument: Sendable, Equatable {");
out.push("    public let name: String");
out.push("    public let uri: String /* spaceo://docs/<name> */");
out.push("    public let title: String");
out.push("    public let markdown: String");
out.push("}");
out.push("");
out.push("/// One MCP prompt backed by a playbook document.");
out.push("public struct PlaybookPrompt: Sendable {");
out.push("    public let name: String");
out.push("    public let description: String");
out.push("    public let documentName: String");
out.push("    public let arguments: [(name: String, description: String, required: Bool)]");
out.push("}");
out.push("");
out.push("public enum Playbook {");
out.push("    public static let documents: [PlaybookDocument] = [");
for (const document of documents) {
  out.push("        PlaybookDocument(");
  out.push(`            name: ${swiftString(document.name)},`);
  out.push(`            uri: ${swiftString(document.uri)},`);
  out.push(`            title: ${swiftString(document.title)},`);
  out.push(`            markdown: ${rawLiteral(document.markdown)}`);
  out.push("        ),");
}
out.push("    ]");
out.push("");
out.push("    public static let prompts: [PlaybookPrompt] = [");
for (const prompt of prompts) {
  out.push("        PlaybookPrompt(");
  out.push(`            name: ${swiftString(prompt.name)},`);
  out.push(`            description: ${swiftString(prompt.description)},`);
  out.push(`            documentName: ${swiftString(prompt.documentName)},`);
  out.push("            arguments: [");
  for (const argument of prompt.arguments) {
    out.push(
      `                (name: ${swiftString(argument.name)}, description: ${swiftString(argument.description)}, required: ${argument.required ? "true" : "false"}),`,
    );
  }
  out.push("            ]");
  out.push("        ),");
}
out.push("    ]");
out.push("}");
out.push("");

writeFileSync(outputPath, out.join("\n"));
console.log(`wrote ${outputPath} (${documents.length} documents, ${prompts.length} prompts)`);
